import { randomUUID } from 'node:crypto'
import { client, parity, prodApp, signUp } from './parity.mjs'
import { lighthouse } from './lighthouse.mjs'
import { BENCH_DIR, TOOLS_IMAGE, docker, dockerAsync, log, memoryMiB, OHA_IMAGE, psql, RUNS, sleep, timed, waitForHttp } from './lib.mjs'
import { PRODUCTION, VARIANTS, checkout } from './variants.mjs'

const COMPOSE = ['compose', '-f', `${BENCH_DIR}/compose.yaml`]
const NOTES = 10_000
const WARMUP = '5s'
const DURATION = '20s'
const CONNECTIONS = 50
const FIXED_RATE = 50
const IDLE_SAMPLES = 5
const BENCH_EMAIL = 'bench@example.com'

const compose = (...args) => docker(...COMPOSE, ...args)
const container = variant => `bench-${variant}-1`

function buildImages() {
  for (const variant of PRODUCTION) {
    log(`building ${VARIANTS[variant].image}`)
    docker('build', '--target', 'prod', '-t', VARIANTS[variant].image, checkout(variant))
  }
  docker('build', '-t', TOOLS_IMAGE, `${BENCH_DIR}/tools`)
}

function resetDatabase(variant) {
  psql('postgres', `DROP DATABASE IF EXISTS ${variant} WITH (FORCE)`)
  psql('postgres', `CREATE DATABASE ${variant}`)
}

async function coldStart(variant) {
  compose('rm', '--stop', '--force', variant)
  resetDatabase(variant)
  return timed(async () => {
    compose('up', '-d', '--no-deps', variant)
    await waitForHttp(`${prodApp(variant).url}/health`)
  })
}

function seed(variant) {
  psql(variant, `INSERT INTO notes (owner_id, title, body)
    SELECT u.id, 'Seeded note ' || n, 'Generated by the seed command, number ' || n || ' of ${NOTES}.'
    FROM users u, generate_series(1, ${NOTES}) n WHERE u.email = '${BENCH_EMAIL}'`)
  psql(variant, `INSERT INTO audit_events (actor_id, action, entity, entity_id) SELECT owner_id, 'created', 'note', id FROM notes`)
  return Number(psql(variant, `SELECT id FROM notes ORDER BY id OFFSET ${NOTES / 2} LIMIT 1`))
}

async function oha(args) {
  const output = await dockerAsync('run', '--rm', '--network', 'bench_default', OHA_IMAGE, '--no-tui', '--output-format', 'json', ...args)
  const json = JSON.parse(output)
  const ms = seconds => Math.round(seconds * 100_000) / 100
  return {
    rps: Math.round(json.summary.requestsPerSec),
    p50: ms(json.latencyPercentiles.p50),
    p95: ms(json.latencyPercentiles.p95),
    p99: ms(json.latencyPercentiles.p99),
    successRate: json.summary.successRate,
    statuses: json.statusCodeDistribution,
  }
}

async function load(variant, path, cookie) {
  const target = `http://${variant}:8080${path}`
  const headers = ['-H', `Cookie: ${cookie}`]
  await oha(['-z', WARMUP, '-c', String(CONNECTIONS), ...headers, target])
  let peak = 0
  const sampler = setInterval(async () => { peak = Math.max(peak, await memoryMiB(container(variant))) }, 1000)
  const throughput = await oha(['-z', DURATION, '-c', String(CONNECTIONS), ...headers, target])
  clearInterval(sampler)
  const fixedRate = await oha(['-z', DURATION, '-c', String(CONNECTIONS), '-q', String(FIXED_RATE), '--latency-correction', ...headers, target])
  return { throughput, fixedRate, peakMemoryMiB: peak }
}

async function signInLatency(variant, password) {
  const app = prodApp(variant)
  const body = JSON.stringify(app.credentials({ email: BENCH_EMAIL, password }))
  return oha(['-n', '30', '-c', '1', '-m', 'POST', '-H', 'content-type: application/json', '-H', `origin: ${app.origin}`, '-d', body, `http://${variant}:8080/api/auth/sign-in`])
}

async function prepare(variant) {
  const password = randomUUID()
  const session = await signUp(prodApp(variant), BENCH_EMAIL, password)
  const noteId = seed(variant)
  const total = (await client(prodApp(variant), session.pair)('GET', '/api/notes?page=1')).json?.total
  if (total !== NOTES) throw new Error(`${variant} shows ${total} notes, expected ${NOTES}`)
  return { password, cookie: session.pair, noteId }
}

async function measure(variant, result) {
  result.imageBytes = Number(docker('image', 'inspect', '--format', '{{.Size}}', VARIANTS[variant].image))
  await sleep(10_000)
  result.idleMemoryMiB = []
  for (let sample = 0; sample < IDLE_SAMPLES; sample++) {
    result.idleMemoryMiB.push(await memoryMiB(container(variant)))
    await sleep(1000)
  }
  const { password, cookie, noteId } = await prepare(variant)
  log(`parity ${variant}`)
  result.parity = await parity(prodApp(variant))
  const paths = ['/notes?page=1', '/notes?page=250', `/notes/${noteId}`, '/api/notes?page=1']
  for (let run = 0; run < RUNS; run++) {
    for (const path of paths) {
      log(`load ${variant} ${path} (${run + 1}/${RUNS})`)
      const key = path.replace(String(noteId), ':id')
      result.load[key] ??= []
      result.load[key].push(await load(variant, path, cookie))
    }
    result.signIn.push(await signInLatency(variant, password))
  }
  log(`lighthouse ${variant}`)
  result.lighthouse = lighthouse(variant, cookie)
}

export async function production() {
  buildImages()
  process.env.NUXT_SESSION_PASSWORD = randomUUID() + randomUUID()
  compose('down', '--volumes', '--remove-orphans')
  compose('up', '-d', '--wait', 'db')
  const results = Object.fromEntries(PRODUCTION.map(variant => [variant, { coldStartMs: [], load: {}, signIn: [] }]))
  for (let run = 0; run < RUNS; run++) {
    for (const variant of run % 2 ? [...PRODUCTION].reverse() : PRODUCTION) {
      log(`cold start ${variant} (${run + 1}/${RUNS})`)
      results[variant].coldStartMs.push(await coldStart(variant))
    }
  }
  for (const variant of PRODUCTION) {
    await measure(variant, results[variant])
  }
  compose('down', '--volumes', '--remove-orphans')
  return results
}
