import { randomUUID } from 'node:crypto'
import { APPS, client, parity, signUp } from './parity.mjs'
import { lighthouse } from './lighthouse.mjs'
import { BENCH_DIR, docker, dockerAsync, log, memoryMiB, OHA_IMAGE, psql, REPO_DIR, RUNS, sleep, timed, waitForHttp } from './lib.mjs'

const COMPOSE = ['compose', '-f', `${BENCH_DIR}/compose.yaml`]
const NOTES = 10_000
const WARMUP = '5s'
const DURATION = '20s'
const CONNECTIONS = 50
const FIXED_RATE = 200
const BENCH_EMAIL = 'bench@example.com'

const compose = (...args) => docker(...COMPOSE, ...args)
const container = app => `bench-${app}-1`

function buildImages() {
  log('building production images')
  docker('build', '--target', 'prod', '-t', 'rust-starter:prod', REPO_DIR)
  docker('build', '--target', 'prod', '-t', 'nuxt-starter:prod', `${REPO_DIR}/bench/nuxt`)
  docker('build', '-t', 'bench-tools:1', `${BENCH_DIR}/tools`)
}

function resetDatabase(app) {
  psql('postgres', `DROP DATABASE IF EXISTS ${app} WITH (FORCE)`)
  psql('postgres', `CREATE DATABASE ${app}`)
}

async function coldStart(app) {
  compose('rm', '--stop', '--force', app)
  resetDatabase(app)
  return timed(async () => {
    compose('up', '-d', '--no-deps', app)
    await waitForHttp(`${APPS[app].url}/health`)
  })
}

function seed(app) {
  psql(app, `INSERT INTO notes (owner_id, title, body)
    SELECT u.id, 'Seeded note ' || n, 'Generated by the seed command, number ' || n || ' of ${NOTES}.'
    FROM users u, generate_series(1, ${NOTES}) n WHERE u.email = '${BENCH_EMAIL}'`)
  psql(app, `INSERT INTO audit_events (actor_id, action, entity, entity_id) SELECT owner_id, 'created', 'note', id FROM notes`)
  return Number(psql(app, `SELECT id FROM notes ORDER BY id OFFSET ${NOTES / 2} LIMIT 1`))
}

async function oha(args) {
  const output = await dockerAsync('run', '--rm', '--network', 'bench_default', OHA_IMAGE, '--no-tui', '--output-format', 'json', ...args)
  const json = JSON.parse(output)
  const ms = seconds => Math.round(seconds * 100_000) / 100
  return {
    rps: Math.round(json.summary.requestsPerSec),
    p50: ms(json.latencyPercentiles.p50),
    p95: ms(json.latencyPercentiles.p95),
    p99: ms(json.latencyPercentiles.p99),
    successRate: json.summary.successRate,
    statuses: json.statusCodeDistribution,
  }
}

async function load(app, path, cookie) {
  const target = `http://${app}:8080${path}`
  const headers = ['-H', `Cookie: ${cookie}`]
  await oha(['-z', WARMUP, '-c', String(CONNECTIONS), ...headers, target])
  let peak = 0
  const sampler = setInterval(async () => { peak = Math.max(peak, await memoryMiB(container(app))) }, 1000)
  const throughput = await oha(['-z', DURATION, '-c', String(CONNECTIONS), ...headers, target])
  clearInterval(sampler)
  const fixedRate = await oha(['-z', DURATION, '-c', String(CONNECTIONS), '-q', String(FIXED_RATE), '--latency-correction', ...headers, target])
  return { throughput, fixedRate, peakMemoryMiB: peak }
}

async function signInLatency(app, password) {
  const body = JSON.stringify(APPS[app].credentials({ email: BENCH_EMAIL, password }))
  return oha(['-n', '30', '-c', '1', '-m', 'POST', '-H', 'content-type: application/json', '-H', `origin: ${APPS[app].origin}`, '-d', body, `http://${app}:8080/api/auth/sign-in`])
}

async function prepare(app) {
  const password = randomUUID()
  const session = await signUp(APPS[app], BENCH_EMAIL, password)
  const noteId = seed(app)
  const total = (await client(APPS[app], session.pair)('GET', '/api/notes?page=1')).json?.total
  if (total !== NOTES) throw new Error(`${app} shows ${total} notes, expected ${NOTES}`)
  return { password, cookie: session.pair, noteId }
}

export async function production() {
  buildImages()
  process.env.NUXT_SESSION_PASSWORD = randomUUID() + randomUUID()
  compose('down', '--volumes', '--remove-orphans')
  compose('up', '-d', '--wait', 'db')
  const apps = ['rust', 'nuxt']
  const results = Object.fromEntries(apps.map(app => [app, { coldStartMs: [], load: {}, signIn: [] }]))
  for (let run = 0; run < RUNS; run++) {
    for (const app of apps) {
      log(`cold start ${app} (${run + 1}/${RUNS})`)
      results[app].coldStartMs.push(await coldStart(app))
    }
  }
  for (const app of apps) {
    const result = results[app]
    result.imageBytes = Number(docker('image', 'inspect', '--format', '{{.Size}}', `${app}-starter:prod`))
    await sleep(5000)
    result.idleMemoryMiB = await memoryMiB(container(app))
    const { password, cookie, noteId } = await prepare(app)
    log(`parity ${app}`)
    result.parity = await parity(APPS[app])
    const paths = ['/notes?page=1', '/notes?page=250', `/notes/${noteId}`, '/api/notes?page=1']
    for (let run = 0; run < RUNS; run++) {
      for (const path of paths) {
        log(`load ${app} ${path} (${run + 1}/${RUNS})`)
        result.load[path.replace(String(noteId), ':id')] ??= []
        result.load[path.replace(String(noteId), ':id')].push(await load(app, path, cookie))
      }
      result.signIn.push(await signInLatency(app, password))
    }
    log(`lighthouse ${app}`)
    result.lighthouse = lighthouse(app, cookie)
  }
  compose('down', '--volumes', '--remove-orphans')
  return results
}
