import { eq } from 'drizzle-orm'
import { createDb } from '../server/db/client'
import { users } from '../server/db/schema'
import { trustedActor } from '../server/utils/actor'
import { insertNotes } from '../server/utils/notes'

const SEED_CHUNK = 1_000
const [email, countText] = process.argv.slice(2)
const count = Number(countText)
if (!email || !Number.isInteger(count) || count < 1) {
  throw new Error('Usage: npm run seed -- <email> <count>')
}
const url = process.env.NUXT_DATABASE_URL
if (!url) {
  throw new Error('NUXT_DATABASE_URL must be set')
}
const db = createDb(url)
const [owner] = await db.select().from(users).where(eq(users.email, email.trim().toLowerCase()))
if (!owner) {
  throw new Error(`no account for ${email}; sign up first`)
}
for (let inserted = 0; inserted < count; inserted += SEED_CHUNK) {
  const chunk = Math.min(SEED_CHUNK, count - inserted)
  const inputs = Array.from({ length: chunk }, (_, index) => {
    const n = inserted + index + 1
    return { title: `Seeded note ${n}`, body: `Generated by the seed command, number ${n} of ${count}.` }
  })
  await insertNotes(db, trustedActor(owner.id), inputs)
  console.log(`Inserted ${inserted + chunk} of ${count}`)
}
await db.$client.end()
