use anyhow::Context;
use sea_orm::{ColumnTrait, EntityTrait, QueryFilter};

use super::{auth::Actor, config::Config, db, entities::user, notes};
use crate::api::NoteInput;

const SEED_CHUNK: u64 = 1_000;

pub async fn seed(email: &str, count: u64) -> anyhow::Result<()> {
    let config = Config::from_env()?;
    let db = db::connect(&config.database_url).await?;
    let owner = user::Entity::find()
        .filter(user::Column::Email.eq(email.trim().to_lowercase()))
        .one(&db)
        .await?
        .with_context(|| format!("no account for {email}; sign up first"))?;
    let actor = Actor::trusted(owner.id);
    let mut inserted = 0;
    while inserted < count {
        let chunk = SEED_CHUNK.min(count - inserted);
        let inputs = (inserted + 1..=inserted + chunk)
            .map(|n| NoteInput {
                title: format!("Seeded note {n}"),
                body: format!("Generated by the seed command, number {n} of {count}."),
            })
            .collect();
        notes::insert_many(&db, actor, inputs).await?;
        inserted += chunk;
        println!("Inserted {inserted} of {count}");
    }
    Ok(())
}
